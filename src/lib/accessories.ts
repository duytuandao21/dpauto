/** Lowercase without Vietnamese accents, so "camera hanh trinh" finds "Camera hành trình". */
export const searchText = (value: string) =>
  value
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .replace(/đ/gi, "d")
    .toLowerCase()
    .trim();

export const accessorySorts = [
  { value: "newest", label: "Mới nhất" },
  { value: "name-asc", label: "Tên A → Z" },
  { value: "name-desc", label: "Tên Z → A" },
] as const;
export type AccessorySort = (typeof accessorySorts)[number]["value"];

/** Brand + category + accent-insensitive search; "newest" keeps catalogue order (newest first). */
export function filterAccessories({
  query = "",
  brand = "",
  category = "",
  sort = "newest",
}: {
  query?: string;
  brand?: string;
  category?: string;
  sort?: AccessorySort;
}) {
  const words = searchText(query).split(/\s+/).filter(Boolean);
  const list = accessories.filter(
    (p) =>
      (!brand || p.brand === brand) &&
      (!category || p.category === category) &&
      words.every((w) =>
        searchText(
          `${p.name} ${p.brand} ${p.category} ${p.description}`,
        ).includes(w),
      ),
  );
  if (sort === "newest") return list;
  const byName = list.sort((a, b) => a.name.localeCompare(b.name, "vi"));
  return sort === "name-desc" ? byName.reverse() : byName;
}
